import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const read=(path)=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const panel=read('app/(crm)/notifications/NotificationsCallsPanel.tsx')
const actions=read('app/(crm)/notifications/OfficeRingCentralActions.tsx')
const sync=read('app/api/ringcentral/sync/route.ts')
const source=read('lib/ringcentral.ts')
const voice=read('app/api/ringcentral/voicemails/[id]/route.ts')
const calendar=read('app/(crm)/dashboard/DashboardCalendar.tsx')
const page=read('app/(crm)/calendar/page.tsx')

test('Office CRM includes matched and UNKNOWN inbound, outbound, missed and voicemails',()=>{
 assert.match(panel,/\['all','All Activity'\]/)
 assert.match(panel,/\['inbound','Inbound Answered'\]/)
 assert.match(panel,/\['outbound','Outbound'\]/)
 assert.match(panel,/\['missed','Missed Calls'\]/)
 assert.match(panel,/\['voicemail','Voicemails'\]/)
 assert.match(panel,/\.eq\('agency_id',profile\.agency_id\)/)
 assert.match(panel,/\.is\('hidden_at',null\)/)
 assert.doesNotMatch(panel,/\.not\('client_id'/)
 assert.match(panel,/name\(person\)/)
 assert.match(panel,/Unknown Caller/)
})
test('All days start CLOSED and group by America/Chicago day, not browser local date',()=>{
 assert.match(panel,/timeZone:'America\/Chicago'/)
 assert.match(panel,/const groups=new Map<string,Item\[\]>\(\)/)
 assert.match(panel,/<details className="office-ring-day" key=/)
 assert.doesNotMatch(panel,/<details[^>]*open=/)
 assert.match(panel,/<summary>/)
})
test('Delete and notes are agency-scoped, and original RingCentral records are preserved',()=>{
 assert.match(actions,/Delete from the Office CRM/)
 assert.match(actions,/method:'DELETE'/)
 assert.match(actions,/saveNote/)
 assert.match(actions,/method:'PATCH'/)
 assert.match(actions,/window\.confirm/)
 assert.match(voice,/hidden_at:new Date\(\)\.toISOString\(\)/)
 assert.match(voice,/\.eq\('agency_id',profile\.agency_id\)/)
 assert.match(sync,/\.upsert\(chunk,\{onConflict:'agency_id,source_message_id'\}\)/)
 assert.doesNotMatch(sync,/hidden_at:null/)
})
test('Office sync retains calls without client record and pages call logs',()=>{
 assert.match(source,/for \(let page = 1; page <= maxPages; page\+\+\)/)
 assert.match(sync,/listRecentRingCentralCalls\(accessToken, 90, 10\)/)
 assert.match(sync,/client_id: normalizedExternal \? clientByPhone\.get\(normalizedExternal\) \|\| null : null/)
 assert.match(sync,/voicemails:voicemailSaved/)
})
test('Appointment is opened and prefilled from the specific call or voicemail',()=>{
 assert.match(actions,/from_call:'1'/)
 assert.match(actions,/call_phone:phone/)
 assert.match(actions,/call_client/)
 assert.match(calendar,/params\.get\('from_call'\)!=='1'/)
 assert.match(calendar,/setEditorOpen\(true\)/)
 assert.match(calendar,/client_id:clientId/)
 assert.match(page,/params\.from_call==='1'/)
 assert.match(page,/calendar_agent:selected\.id/)
})
test('Voicemail audio rechecks message access and restricts audio source',()=>{
 assert.match(voice,/\.is\('hidden_at',null\)/)
 assert.match(voice,/getCrmSession/)
 assert.match(voice,/message-store/)
 assert.match(voice,/ringcentral\\\.com/)
})
